package org.example.pulse_ai.domain.product;

import java.util.List;

/** Сюжетная арка витрины Pulse — не «мы крутые», а серия эпизодов. */
public final class ProductStoryPrompts {

    private ProductStoryPrompts() {
    }

    public record BeatOutline(String key, String title, String outline) {
    }

    /** Дефолтная арка «Знакомство с Pulse» — 6 эпизодов. */
    public static List<BeatOutline> introArcBeats() {
        return List.of(
                new BeatOutline("HOOK", "Эпизод 1 · Знакомая боль",
                        """
                        Открой арку. Админ канала вечером смотрит статистику и не понимает,
                        что постить завтра. Не продавай продукт в лоб — покажи сцену и узнавание.
                        Намёк: есть инструмент, который снимает эту рутину. Без схем и «как устроено»."""),
                new BeatOutline("PROMISE", "Эпизод 2 · Что меняется",
                        """
                        Продолжение сюжета: что если ссылка на канал за минуты даёт ясность —
                        где просадка, что заходит, какие идеи на неделю. Говори языком результата.
                        Интрига: это только вход. Не перечисляй модули и архитектуру."""),
                new BeatOutline("RITUAL", "Эпизод 3 · Как это ощущается",
                        """
                        Мини-путь героя: кинул ссылку → увидел картину → выбрал идею → пост готов.
                        Три шага, живо. Читатель должен представить себя в роли. Без скринов-цифр-фейка."""),
                new BeatOutline("ALLY", "Эпизод 4 · Кто рядом",
                        """
                        Появление «ассистента» как персонажа: следит за диалогами вокруг канала,
                        пока ты занят. Тон: напарник, не шпион. Никаких CRM/скаутов/прокси в тексте."""),
                new BeatOutline("GROWTH", "Эпизод 5 · Не любой трафик",
                        """
                        Сдвиг: рост — это не «налить охваты», а находить тех, кому продукт реально нужен.
                        Мягко, с достоинством. Оставь ощущение, что у нас есть свой способ — без рецепта."""),
                new BeatOutline("INVITE", "Эпизод 6 · Дверь открыта",
                        """
                        Финал арки: приглашение зайти в бота, попробовать разбор, остаться в канале —
                        дальше будут апдейты как у большой игры. Вопрос к аудитории + один CTA на бота.
                        Без хвастовства «мы ахуенные».""")
        );
    }

    public static final String BEAT_SYSTEM = """
            Ты — сценарист product-канала Pulse AI.
            Пишешь ОДИН пост — эпизод сюжетной арки (не рекламный вброс).

            Правила:
            • 450–850 символов, одна сцена / один поворот
            • Есть «вчера→сегодня» ощущение продолжения (если дан предыдущий эпизод)
            • Польза и интрига; НЕ раскрывай внутренности продукта
            • Запрещено: прокси, роли аккаунтов, лимиты ЛС, CRM, названия модулей, «как копировать»
            • Максимум 2 эмодзи. Без markdown-заголовков.
            • В конце — тонкий крючок к следующему эпизоду ИЛИ мягкий CTA (только в финале арки)

            Ответ — ТОЛЬКО текст поста.""";

    public static String beatUserPrompt(BeatOutline beat, String premise, String previousPostsSummary, int index, int total) {
        return """
                Арка: %s

                Эпизод %d из %d
                Название: %s
                Ключ: %s
                ТЗ эпизода:
                %s

                Уже вышло раньше (не повторяй, продолжай сюжет):
                %s

                Напиши пост-эпизод.
                """.formatted(
                premise,
                index,
                total,
                beat.title(),
                beat.key(),
                beat.outline(),
                previousPostsSummary == null || previousPostsSummary.isBlank()
                        ? "(это первый эпизод)"
                        : previousPostsSummary
        );
    }
}
